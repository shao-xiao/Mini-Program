CREATE TABLE equipment (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    code VARCHAR(32) NOT NULL COMMENT '业务编号',
    equipment_name VARCHAR(100) NOT NULL COMMENT '设备名称',
    equipment_code VARCHAR(64) NULL COMMENT '设备编号',
    equipment_type VARCHAR(32) NOT NULL DEFAULT 'OTHER' COMMENT '设备类型',
    location VARCHAR(120) NULL COMMENT '位置',
    manufacturer VARCHAR(100) NULL COMMENT '厂家',
    model VARCHAR(100) NULL COMMENT '型号',
    install_date DATE NULL COMMENT '安装日期',
    status VARCHAR(32) NOT NULL DEFAULT 'NORMAL' COMMENT '状态',
    remark VARCHAR(500) NULL COMMENT '备注',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by BIGINT NULL COMMENT '创建人',
    updated_by BIGINT NULL COMMENT '更新人',
    deleted TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    UNIQUE KEY uk_equipment_code (code),
    UNIQUE KEY uk_equipment_equipment_code (equipment_code),
    KEY idx_equipment_type (equipment_type),
    KEY idx_equipment_status (status),
    KEY idx_equipment_location (location),
    KEY idx_equipment_deleted_updated (deleted, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='设备台账';
