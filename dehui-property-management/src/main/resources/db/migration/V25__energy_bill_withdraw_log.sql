CREATE TABLE IF NOT EXISTS energy_bill_operation_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT 'Primary key',
  code VARCHAR(64) NOT NULL COMMENT 'Operation code',
  reading_id BIGINT NOT NULL COMMENT 'Energy reading id',
  bill_id BIGINT DEFAULT NULL COMMENT 'Linked finance bill id',
  action VARCHAR(64) NOT NULL COMMENT 'Operation action',
  reason VARCHAR(500) DEFAULT NULL COMMENT 'Operation reason',
  result_status VARCHAR(32) NOT NULL COMMENT 'Operation result',
  message VARCHAR(500) DEFAULT NULL COMMENT 'Operation message',
  operator_id BIGINT DEFAULT NULL COMMENT 'Operator id',
  operator_name VARCHAR(64) DEFAULT NULL COMMENT 'Operator name',
  operated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Operation time',
  status VARCHAR(32) NOT NULL DEFAULT 'ENABLED' COMMENT 'Status',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by BIGINT DEFAULT NULL,
  updated_by BIGINT DEFAULT NULL,
  deleted TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY uk_energy_bill_log_code (code),
  KEY idx_energy_bill_log_reading (reading_id),
  KEY idx_energy_bill_log_bill (bill_id),
  KEY idx_energy_bill_log_action (action),
  KEY idx_energy_bill_log_time (operated_at)
) COMMENT='Energy reading bill operation log';
