CREATE TABLE inspection_record (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  code VARCHAR(64) NOT NULL COMMENT '巡检编号',
  inspection_date DATE NOT NULL COMMENT '巡检日期',
  inspector VARCHAR(64) NOT NULL COMMENT '巡检人',
  inspection_type VARCHAR(32) NOT NULL DEFAULT 'DAILY' COMMENT '巡检类型',
  area VARCHAR(128) NOT NULL COMMENT '区域/地点',
  target VARCHAR(128) NOT NULL COMMENT '巡检对象',
  result VARCHAR(32) NOT NULL DEFAULT 'NORMAL' COMMENT '巡检结果',
  problem_description VARCHAR(1000) DEFAULT NULL COMMENT '问题描述',
  action_taken VARCHAR(1000) DEFAULT NULL COMMENT '处理措施',
  inspection_status VARCHAR(32) NOT NULL DEFAULT 'OPEN' COMMENT '巡检状态',
  status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  created_by BIGINT DEFAULT NULL COMMENT '创建人',
  updated_by BIGINT DEFAULT NULL COMMENT '更新人',
  deleted TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  remark VARCHAR(500) DEFAULT NULL COMMENT '备注',
  PRIMARY KEY (id),
  UNIQUE KEY uk_inspection_code (code, deleted),
  KEY idx_inspection_date (inspection_date),
  KEY idx_inspection_inspector (inspector),
  KEY idx_inspection_type (inspection_type),
  KEY idx_inspection_result (result),
  KEY idx_inspection_status (inspection_status),
  KEY idx_inspection_target (target),
  KEY idx_inspection_deleted_updated (deleted, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='巡检记录表';
