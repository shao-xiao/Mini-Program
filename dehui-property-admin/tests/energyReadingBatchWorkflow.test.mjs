  assert.match(recordPage, /openMonthlyTaskDialog/)
  assert.match(recordPage, /generateMonthlyEnergyReadings\(/)
  assert.match(recordPage, /exportReadingTemplate/)
  assert.match(recordPage, /downloadEnergyReadingTemplate/)
  assert.match(recordPage, /downloadBlob/)
  assert.match(recordPage, /showSaveFilePicker/)
  assert.doesNotMatch(recordPage, /templateDownloadUrl/)
  assert.doesNotMatch(recordPage, /templateDownloadName/)
  assert.doesNotMatch(recordPage, /templateCsvContent/)
  assert.doesNotMatch(recordPage, /copyTemplateContent/)
  assert.match(recordPage, /@workspace-file="handleImportReadingFile"/)
  assert.match(recordPage, /handleImportReadingFile/)
  assert.match(recordPage, /mapReadingImportRow/)
  assert.match(recordPage, /fallbackReadingImportValue/)
  assert.match(recordPage, /normalizeImportDate/)
  assert.match(recordPage, /importEnergyReadingValues\(/)
  assert.match(recordPage, /batchGenerateBills/)
  assert.match(recordPage, /batchConfirmEnergyChargeBases\(/)
  assert.match(workspaceConfig, /id: 'import'.*kind: 'import'.*label: '导入读数'/)
