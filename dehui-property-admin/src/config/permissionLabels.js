export function permissionCode(permission = {}) {
  return permission.permissionCode || permission.code || ''
}

export function formatPermissionLabel(permission = {}) {
  const code = permissionCode(permission)
  if (permissionLabels[code]) {
    return permissionLabels[code]
  }
  return permission.permissionName || permission.name || code || '未命名权限'
}
